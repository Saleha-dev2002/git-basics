# Numeric Sequences using range()

# Part 1: Print Even Numbers from 2 to 10
print("--- Even Numbers (2 to 10) ---")
for num in range(2, 11, 2):
    print(num)

print("\n--- Rocket Countdown (5 to 1) ---")
# Part 2: Reverse Countdown from 5 to 1
for count in range(5, 0, -1):
    print(count)

print("🚀 Blast Off!")
